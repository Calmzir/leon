#!/usr/bin/env python3
"""Cuts the Den's lions for the phone from the desktop's sheets.

Run from the repository root, with Pillow installed:

    python3 mobile/scripts/den-lions.py

For each agent's colour it writes, to mobile/assets/den, the front-facing row
of the first three styles of every body (ten frames of 16 by 32), with the
mane's three key colours replaced by that colour, enlarged eight times
without smoothing; and src/ui/denSheets.ts, which lists them. The sheets are
crates/leon-den/assets/lions (see LICENSE-pixel-agents-MIT beside them).
"""
import colorsys
import os

from PIL import Image

SOURCE = "crates/leon-den/assets/lions"
OUT = "mobile/assets/den"
SHEETS_TS = "mobile/src/ui/denSheets.ts"
BODIES, STYLES, SCALE = 5, 3, 8
# The mane as it is painted in the sheets: light, middle, dark.
KEYS = {(255, 0, 255): "light", (200, 0, 200): "mid", (120, 0, 120): "dark"}
# The agents' colours of the dark theme (mobile/src/theme/tokens.ts).
TINTS = {"claude": "#D97757", "codex": "#FAFAF9", "opencode": "#F1ECEC", "other": "#A8A29E"}


def ramp(colour):
    """The three steps of a mane in a colour, as crates/leon-den/src/paint.rs makes them."""
    r, g, b = (int(colour[i : i + 2], 16) / 255 for i in (1, 3, 5))
    hue, light, saturation = colorsys.rgb_to_hls(r, g, b)
    if saturation < 0.12:
        # A grey has no hue: the warm one of fur, faintly.
        hue, saturation = 32 / 360, 0.16
    else:
        saturation = min(saturation, 0.85)
    middle = min(max(light, 0.26), 0.74)

    def rgb(lightness, sat):
        return tuple(round(c * 255) for c in colorsys.hls_to_rgb(hue, min(max(lightness, 0), 1), sat))

    return {
        "light": rgb(middle + 0.13, saturation * 0.9),
        "mid": rgb(middle, saturation),
        "dark": rgb(middle - 0.15, min(saturation * 1.1, 1)),
    }


def main():
    os.makedirs(OUT, exist_ok=True)
    names = {tint: [] for tint in TINTS}
    for tint, colour in TINTS.items():
        steps = ramp(colour)
        for body in range(BODIES):
            for style in range(STYLES):
                sheet = Image.open(f"{SOURCE}/lion_{body}_{style}.png").convert("RGBA")
                row = sheet.crop((0, 0, 160, 32))
                pixels = row.load()
                for y in range(row.height):
                    for x in range(row.width):
                        r, g, b, a = pixels[x, y]
                        step = KEYS.get((r, g, b))
                        if step and a > 0:
                            pixels[x, y] = steps[step] + (a,)
                name = f"{tint}_{body}_{style}.png"
                row.resize((row.width * SCALE, row.height * SCALE), Image.NEAREST).save(
                    os.path.join(OUT, name), optimize=True
                )
                names[tint].append(name)
    lines = [
        "// The lions of the Den, facing the front: one row of ten frames each, cut",
        "// from the desktop's sheets (crates/leon-den/assets/lions), their mane in the",
        "// colour of an agent, enlarged eight times so that they stay sharp.",
        "// Generated by mobile/scripts/den-lions.py: do not edit.",
        "import type { ImageSourcePropType } from 'react-native';",
        "",
        f"export const BODIES = {BODIES};",
        f"export const STYLES = {STYLES};",
        "",
        "export const SHEETS: Record<string, ImageSourcePropType[]> = {",
    ]
    for tint, files in names.items():
        lines.append(f"  {tint}: [")
        lines.extend(f"    require('../../assets/den/{name}')," for name in files)
        lines.append("  ],")
    lines.append("};")
    with open(SHEETS_TS, "w") as out:
        out.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
