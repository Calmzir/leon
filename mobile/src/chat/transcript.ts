// A shared transcript as chat rows, and how it combines with what this device
// already holds of the same conversation.
import type { TranscriptEntry } from '@/link/types';

import type { Message, NoteMessage } from './model';
import type { TurnState } from './reduce';

// --- What a program wrote in the person's place ------------------------------
//
// Agents record in the `user` role whatever reaches the model as a user turn,
// and much of that is written by the harness around the agent. The list below
// was drawn from real histories (Claude Code, Codex, opencode): each tag is a
// block the person never typed. Tags of things the person did put there
// (`pasted_content`, `image`) are not in it and stay part of what they said.

/** The harness's blocks: the pattern of the tag, and the name a note of it goes by. */
const HARNESS_TAGS: [string, string][] = [
  ['task-notification', 'task notification'],
  ['system-reminder', 'system reminder'],
  ['command-(?:name|message|args|contents)', 'command'],
  ['local-command-caveat', 'command'],
  ['local-command-(?:stdout|stderr)', 'command output'],
  ['bash-input', 'shell command'],
  ['bash-(?:stdout|stderr)', 'shell output'],
  ['user-prompt-submit-hook', 'hook output'],
  ['environment_context|environment_details', 'environment'],
  ['user_instructions|INSTRUCTIONS|permissions instructions', 'instructions'],
  ['recommended_plugins', 'plugin list'],
  ['external_codex_apps_writing_block_edits(?:_part_\\d+_of_\\d+)?', 'editor changes'],
  ['in-app-browser-context', 'browser context'],
  ['turn_aborted|user_action', 'interruption'],
];

/** Whole entries the harness writes without a tag. */
const HARNESS_LINES: [RegExp, string][] = [
  [/^\[Request interrupted by user[^\]]*\]$/, 'interruption'],
  [
    /^Caveat: The messages below were generated by the user while running local commands\.[\s\S]*$/,
    'command',
  ],
];

const LABELS = HARNESS_TAGS.map(([tag, label]) => [new RegExp(`^(?:${tag})$`), label] as const);

function harnessLabel(tag: string): string {
  return LABELS.find(([pattern]) => pattern.test(tag))?.[1] ?? 'system';
}

/**
 * An entry that begins with a harness block which never closes: histories
 * clip long messages, and what is left of the block is still the harness's.
 */
const CLIPPED = new RegExp(`^<(${HARNESS_TAGS.map(([tag]) => tag).join('|')})(?:\\s[^<>]*)?>`);

/** One `<tag …>…</tag>` block of the harness, anywhere in a text. */
const BLOCK = new RegExp(
  `<(${HARNESS_TAGS.map(([tag]) => tag).join('|')})(?:\\s[^<>]*)?>[\\s\\S]*?</\\1>`,
  'g',
);

export type Classified = {
  /** What the person wrote, the harness's blocks removed. Empty when none. */
  said: string;
  /** What the harness wrote, with the name of each kind found, in order. */
  note?: { label: string; text: string };
};

/**
 * Separates what a person typed from what a program wrote around it in a
 * `user` entry. An entry that is all harness text has an empty `said`.
 */
export function classifyUserText(text: string): Classified {
  const whole = text.trim();
  for (const [pattern, label] of HARNESS_LINES) {
    if (pattern.test(whole)) return { said: '', note: { label, text: whole } };
  }
  const labels: string[] = [];
  const taken: string[] = [];
  const said = whole
    .replace(BLOCK, (block: string, tag: string) => {
      const label = harnessLabel(tag);
      if (!labels.includes(label)) labels.push(label);
      taken.push(block);
      return '';
    })
    .replace(/\n{3,}/g, '\n\n')
    .trim();
  const clipped = CLIPPED.exec(said);
  if (clipped) {
    const label = harnessLabel(clipped[1]!);
    if (!labels.includes(label)) labels.unshift(label);
    return { said: '', note: { label: labels.join(' + '), text: whole } };
  }
  if (taken.length === 0) return { said: whole };
  return { said, note: { label: labels.join(' + '), text: taken.join('\n') } };
}

function note(id: string, label: string, text: string, at: number): NoteMessage {
  return { id, kind: 'note', label, text, at };
}

/** The rows of a transcript. Ids derive from `prefix` and the position. */
export function transcriptRows(prefix: string, entries: TranscriptEntry[]): Message[] {
  const rows: Message[] = [];
  entries.forEach((entry, index) => {
    const id = `${prefix}:t${index}`;
    const text = entry.text.trim();
    if (!text) return;
    if (entry.role === 'user') {
      const { said, note: aside } = classifyUserText(text);
      // The note first: it is what the person's words were sent along with.
      if (aside) rows.push(note(`${id}n`, aside.label, aside.text, entry.atMs));
      if (said) rows.push({ id, kind: 'user', text: said, at: entry.atMs });
    } else if (entry.role === 'assistant') {
      rows.push({ id, kind: 'assistant', text, at: entry.atMs, streaming: false });
    } else if (entry.role === 'tool') {
      // The history keeps a tool as `Name: what with`, then what came back.
      const [first = '', ...rest] = text.split('\n');
      const named = /^([A-Za-z][\w.-]{0,40}): (.*)$/.exec(first);
      const output = rest.join('\n').trim();
      rows.push({
        id,
        kind: 'tool',
        toolId: id,
        name: named?.[1] ?? 'Tool',
        summary: named?.[2] ?? first,
        status: 'ok',
        ...(output ? { result: output.split('\n')[0], output } : null),
        at: entry.atMs,
      });
    } else {
      // The agent's own plumbing: a summary it continued from, its set-up.
      const label = /^This session is being continued from a previous/.test(text)
        ? 'summary of the earlier conversation'
        : 'system';
      rows.push(note(id, label, text, entry.atMs));
    }
  });
  return rows;
}

/** The rows without the notes: what a chat shows until notes are asked for. */
export function withoutNotes(rows: Message[]): Message[] {
  return rows.some((row) => row.kind === 'note') ? rows.filter((row) => row.kind !== 'note') : rows;
}

/** How long a text is, as a note says it: `840 chars`, `1.2k chars`. */
export function sizeLabel(text: string): string {
  const n = text.length;
  if (n < 1000) return `${n} chars`;
  return `${(n / 1000).toFixed(n < 10000 ? 1 : 0)}k chars`;
}

function sameRow(a: Message, b: Message): boolean {
  if (a === b) return true;
  const keys = Object.keys(a) as (keyof Message)[];
  if (keys.length !== Object.keys(b).length) return false;
  return keys.every((key) => a[key] === b[key]);
}

/**
 * A transcript read again, in terms of the one already shown: every row that
 * did not change is the same object as before, so only what is new or
 * rewritten is drawn again, and a reading that changed nothing is the very
 * list that was there. Rows are matched by position (their ids say it): the
 * other computer appends, rewrites its last entries while the agent is still
 * writing, and now and then imports a session afresh, shorter or different.
 */
export function refreshRows(shown: Message[] | undefined, read: Message[]): Message[] {
  if (!shown) return read;
  const known = new Map(shown.map((row) => [row.id, row]));
  let changed = shown.length !== read.length;
  const rows = read.map((row, at) => {
    const before = known.get(row.id);
    const kept = before && sameRow(before, row) ? before : row;
    if (kept !== shown[at]) changed = true;
    return kept;
  });
  return changed ? rows : shown;
}

/**
 * The rows to show: the transcript, then the turns this device made that the
 * transcript does not have yet. The other computer imports a turn into its
 * history some time after it ran, so for a while a turn exists only here;
 * once the transcript has it, this device's copy is dropped.
 *
 * A local turn is in the transcript when the transcript has a user message
 * with the same text, or anything newer than the turn.
 */
export function mergeTranscript(transcript: Message[], local: Message[]): Message[] {
  if (transcript.length === 0) return local;
  const lastAt = transcript[transcript.length - 1]!.at;
  const prompts = new Set(
    transcript.filter((m) => m.kind === 'user').map((m) => m.text.trim()),
  );

  // Local rows come in turns: a user message and what followed it.
  const turns: Message[][] = [];
  for (const message of local) {
    if (message.kind === 'user' || turns.length === 0) turns.push([message]);
    else turns[turns.length - 1]!.push(message);
  }

  let keepFrom = 0;
  turns.forEach((turn, index) => {
    const head = turn[0]!;
    const known =
      head.at <= lastAt || (head.kind === 'user' && prompts.has(head.text.trim()));
    if (known) keepFrom = index + 1;
  });

  return [...transcript, ...turns.slice(keepFrom).flat()];
}

const EMPTY: Message[] = [];

/**
 * Everything a chat shows, oldest first: the shared transcript, what this
 * device holds beyond it, and the turn in flight, which always comes last
 * whatever the transcript says meanwhile.
 */
export function combineRows(
  transcript: Message[] | undefined,
  local: Message[] | undefined,
  turn: TurnState | undefined,
): Message[] {
  const held = local ?? EMPTY;
  const base = transcript && transcript.length > 0 ? mergeTranscript(transcript, held) : held;
  return turn && turn.items.length > 0 ? [...base, ...turn.items] : base;
}

// --- Is the session moving on the other computer? ----------------------------

/** What is known of a shared session's progress, from one reading to the next. */
export type Activity = {
  /** The session's own stamp and size at the last reading. */
  updatedMs: number;
  messages: number;
  /** When this device last saw either change (its own clock), if it did. */
  changedAt?: number;
};

/** The activity after a new reading; `changed` says the transcript is worth reading again. */
export function nextActivity(
  before: Activity | undefined,
  read: { updatedMs: number; messages: number },
  now: number,
): { activity: Activity; changed: boolean } {
  if (!before) return { activity: { ...read }, changed: true };
  const changed = before.updatedMs !== read.updatedMs || before.messages !== read.messages;
  return {
    activity: { ...read, changedAt: changed ? now : before.changedAt },
    changed,
  };
}

/** How long after a change was seen the session still counts as moving. */
export const LIVE_FOR_MS = 90_000;

/** `live` while a change was seen lately; otherwise how long ago it last moved. */
export function activityWord(activity: Activity | undefined, now: number): { live: boolean; word: string } {
  if (!activity) return { live: false, word: '' };
  if (activity.changedAt !== undefined && now - activity.changedAt < LIVE_FOR_MS) {
    return { live: true, word: 'changing there' };
  }
  const seconds = Math.max(0, Math.round((now - activity.updatedMs) / 1000));
  const ago =
    seconds < 60
      ? `${seconds} s`
      : seconds < 3600
        ? `${Math.round(seconds / 60)} min`
        : seconds < 86400
          ? `${Math.round(seconds / 3600)} h`
          : `${Math.round(seconds / 86400)} d`;
  return { live: false, word: `updated ${ago} ago` };
}
